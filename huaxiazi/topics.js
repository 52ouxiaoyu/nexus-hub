/* ---------- 组合展开 ---------- */
function combosFor(tm){
  var a = POOL[tm.params[0]], out = [];
  if(tm.params.length===1){ a.forEach(function(v){ out.push([v]); }); return out; }
  var b = POOL[tm.params[1]];
  a.forEach(function(x){ b.forEach(function(y){ out.push([x,y]); }); });
  return out;
}

/* ---------- 组装 ---------- */
function buildTopicBank(){
  var bank = [];
  function pushC(c){
    var hs = c.ages.indexOf(15)>-1;
    var guide = hs ? (HS_GUIDES[c.dim] || GUIDES[c.dim]) : GUIDES[c.dim];
    bank.push({t:c.t,dim:c.dim,scene:c.scene,ages:c.ages.slice(),guide:guide,follows:c.follows||[]});
  }
  CURATED.forEach(pushC);
  TEEN_CURATED.forEach(pushC);
  HS_CURATED.forEach(pushC);
  VALUE_KIDS_CURATED.forEach(pushC);
  PRIMARY_CURATED.forEach(pushC);
  PRE_CURATED.forEach(pushC);

  TEMPLATES.forEach(function(tm){
    var combos = combosFor(tm);
    var dims = tm.dims || [tm.dim];
    var scenes = tm.scenes || [tm.scene];
    combos.forEach(function(arg, idx){
      /* 句式变体：variants 存在时按序号轮转，打破同句式换词的注水感 */
      var v = tm.variants ? tm.variants[idx % tm.variants.length] : null;
      var t = (v ? v.text : tm.text).apply(null, arg);
      var fns = v ? v.follows : tm.follows;
      var follows = (fns||[]).map(function(f){ return typeof f==='function' ? f.apply(null,arg) : f; });
      var dim = dims[idx % dims.length];
      var scene = scenes[idx % scenes.length];
      var hs = tm.ages.indexOf(15)>-1;
      bank.push({t:t, dim:dim, scene:scene, ages:tm.ages.slice(), guide:(hs?(HS_GUIDES[dim]||GUIDES[dim]):GUIDES[dim]), follows:follows});
    });
  });

  /* 给每条话题打上稳定索引 */
  bank.forEach(function(b,i){ b.i = i; });
  return bank;
}
